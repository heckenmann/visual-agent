package de.heckenmann.visualagent.release.bundles

import de.heckenmann.visualagent.release.noticeSha256
import de.heckenmann.visualagent.release.safeEvidencePath
import org.apache.commons.compress.archivers.zip.Zip64Mode
import org.apache.commons.compress.archivers.zip.ZipArchiveEntry
import org.apache.commons.compress.archivers.zip.ZipArchiveOutputStream
import java.io.ByteArrayInputStream
import java.io.InputStream
import java.nio.file.Files
import java.nio.file.Path
import java.nio.file.StandardCopyOption
import java.security.MessageDigest
import java.time.LocalDateTime

/** One archive entry backed by an original file or deterministic generated bytes. */
data class BundleEntry(
    /** Safe relative archive name. */
    val name: String,
    /** Original on-disk content, when present. */
    val source: Path? = null,
    /** Generated read-only content, when present. */
    val bytes: ByteArray? = null,
) {
    init {
        require((source == null) != (bytes == null)) { "Bundle entry requires exactly one content source" }
        require(safeEvidencePath(name)) { "Unsafe release material path: $name" }
    }

    /** Opens original content without rewriting its encoding or line endings. */
    fun open(): InputStream = source?.let(Files::newInputStream) ?: ByteArrayInputStream(requireNotNull(bytes))

    /** Returns the content hash used by both manifest and conflict verification. */
    fun sha256(): String =
        source?.let(::noticeSha256) ?: MessageDigest.getInstance("SHA-256").digest(bytes).joinToString("") { "%02x".format(it) }
}

/** Enumerates original files in portable deterministic order and rejects linked inputs. */
internal fun bundleFiles(root: Path): List<BundleEntry> {
    require(!Files.isSymbolicLink(root) && Files.isDirectory(root)) { "Required material directory is missing or linked: $root" }
    return Files.walk(root).use { paths ->
        paths
            .sorted()
            .map { path ->
                require(!Files.isSymbolicLink(path)) { "Linked release material is not allowed: $path" }
                path
            }.filter(Files::isRegularFile)
            .map { path ->
                BundleEntry(root.relativize(path).toString().replace('\\', '/'), source = path)
            }.toList()
    }
}

/** Writes reproducible stored ZIP entries and atomically replaces the output only on success. */
internal fun writeBundleArchive(
    output: Path,
    entries: List<BundleEntry>,
    reviewNotice: String?,
) {
    Files.createDirectories(output.parent)
    val manifest = entries.joinToString("") { "${it.sha256()}  ${it.name}\n" }
    val all =
        entries + BundleEntry("MANIFEST.sha256", bytes = manifest.toByteArray()) +
            if (reviewNotice == null) emptyList() else listOf(BundleEntry("REVIEW-ONLY.txt", bytes = reviewNotice.toByteArray()))
    val temporary = Files.createTempFile(output.parent, ".${output.fileName}.", ".tmp")
    try {
        ZipArchiveOutputStream(temporary).use { archive ->
            archive.setUseZip64(Zip64Mode.AsNeeded)
            archive.setUseLanguageEncodingFlag(false)
            for (item in all) {
                val entry = ZipArchiveEntry(item.name)
                entry.method = ZipArchiveEntry.STORED
                entry.unixMode = 0x81A4
                entry.setTimeLocal(LocalDateTime.of(1980, 1, 1, 0, 0))
                archive.putArchiveEntry(entry)
                item.open().use { it.copyTo(archive, 1024 * 1024) }
                archive.closeArchiveEntry()
            }
        }
        Files.move(temporary, output, StandardCopyOption.ATOMIC_MOVE, StandardCopyOption.REPLACE_EXISTING)
    } finally {
        Files.deleteIfExists(temporary)
    }
}
